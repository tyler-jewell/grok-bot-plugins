#!/usr/bin/env node
/**
 * Embed plugins/skiherd/skills/{healthcheck,setup}/SKILL.md into
 * src/skills.generated.ts so the Worker serves the same text as the repo.
 *
 *   node scripts/embed-skills.mjs --write   # generate the file
 *   node scripts/embed-skills.mjs --check   # exit 1 if the file is stale
 */
import { execSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const names = ["healthcheck", "setup"];
const outPath = join(root, "src/skills.generated.ts");

function readSkill(name) {
  return readFileSync(join(root, "plugins/skiherd/skills", name, "SKILL.md"), "utf8");
}

function gitSha() {
  try {
    return execSync("git rev-parse --short HEAD", { cwd: root, stdio: ["ignore", "pipe", "ignore"] })
      .toString()
      .trim();
  } catch {
    return "local";
  }
}

function generate() {
  const skills = Object.fromEntries(names.map((name) => [name, readSkill(name)]));
  for (const name of names) {
    if (!skills[name] || !skills[name].includes(`name: ${name}`)) {
      throw new Error(`Skill file for ${name} is missing or has the wrong frontmatter name`);
    }
  }
  return (
    "/** Generated by scripts/embed-skills.mjs. Do not edit. */\n" +
    `export const SKILL_NAMES = ${JSON.stringify(names)} as const;\n` +
    `export type SkillName = (typeof SKILL_NAMES)[number];\n` +
    `export const SKILLS: Record<SkillName, string> = ${JSON.stringify(skills, null, 2)};\n` +
    `export const BUILD_INFO = ${JSON.stringify({ gitSha: gitSha() }, null, 2)} as const;\n` +
    `export const MCP_INSTRUCTIONS =\n` +
    JSON.stringify(
      [
        "SkiHerd is a free group ski map. Hosted free by Tyler Jewell, bare minimum, no data kept, everything in a group is deleted 24 hours after creation. Not affiliated with Winter Park Resort.",
        "Before you do anything else, call the healthcheck tool (or follow the healthcheck skill). Do not create, join, or update a group until healthcheck returns ok: true.",
        "If healthcheck fails, stop and tell the human what is down. Do not invent a workaround.",
        "If healthcheck passes, follow the setup skill and walk the human through consent, a one-time location, creating or joining a group, the first heartbeat, and the map link.",
        "Skills are available as prompts (healthcheck, setup), resources (skiherd://skills/healthcheck, skiherd://skills/setup), and the get_skill tool. A bot that only added this MCP URL still has everything it needs.",
      ].join(" "),
    ) +
    ";\n"
  );
}

const mode = process.argv.includes("--check") ? "check" : "write";
const next = generate();
if (mode === "check") {
  let current = "";
  try {
    current = readFileSync(outPath, "utf8");
  } catch {
    console.error("src/skills.generated.ts is missing. Run: node scripts/embed-skills.mjs --write");
    process.exit(1);
  }
  // gitSha changes every commit; compare skill bodies only by re-reading expected skills.
  const currentSkills = current.includes("export const SKILLS") ? current : "";
  const nextSkills = next;
  // For --check, require exact match of skill strings. BUILD_INFO gitSha may differ
  // after a commit, so compare the SKILLS object only.
  const extract = (src) => {
    const match = src.match(/export const SKILLS: Record<SkillName, string> = (\{[\s\S]*?\});/);
    if (!match) throw new Error("could not parse SKILLS from generated file");
    return match[1];
  };
  const extractInstr = (src) => {
    const match = src.match(/export const MCP_INSTRUCTIONS =\n("[\s\S]*?");/);
    if (!match) throw new Error("could not parse MCP_INSTRUCTIONS from generated file");
    return match[1];
  };
  if (extract(currentSkills) !== extract(nextSkills) || extractInstr(current) !== extractInstr(next)) {
    console.error("src/skills.generated.ts is out of date with plugins/skiherd/skills. Run: node scripts/embed-skills.mjs --write");
    process.exit(1);
  }
  console.log("skills embed is up to date");
  process.exit(0);
}

writeFileSync(outPath, next);
console.log("wrote src/skills.generated.ts");
